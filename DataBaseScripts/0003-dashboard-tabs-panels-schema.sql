-- Apply only to the explicitly selected Company database after dashboard schema.
CREATE TABLE IF NOT EXISTS dashboard_tabs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  guid CHAR(36) NOT NULL,
  dashboard_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(150) NOT NULL,
  description TEXT NULL,
  sort_order INT UNSIGNED NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  is_default TINYINT(1) NOT NULL DEFAULT 0,
  active_default_dashboard_id BIGINT UNSIGNED
    GENERATED ALWAYS AS (CASE WHEN status = 'ACTIVE' AND is_default = 1 THEN dashboard_id ELSE NULL END) STORED,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  created_by BIGINT UNSIGNED NOT NULL,
  updated_at DATETIME(3) NULL,
  updated_by BIGINT UNSIGNED NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dashboard_tabs_guid (guid),
  UNIQUE KEY uq_dashboard_tabs_active_default (active_default_dashboard_id),
  KEY idx_dashboard_tabs_dashboard (dashboard_id),
  KEY idx_dashboard_tabs_dashboard_order (dashboard_id, sort_order),
  KEY idx_dashboard_tabs_dashboard_status (dashboard_id, status),
  CONSTRAINT chk_dashboard_tabs_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT chk_dashboard_tabs_default CHECK (is_default IN (0, 1)),
  CONSTRAINT fk_dashboard_tabs_dashboard FOREIGN KEY (dashboard_id)
    REFERENCES dashboards (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS dashboard_panels (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  guid CHAR(36) NOT NULL,
  tab_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(200) NOT NULL,
  description TEXT NULL,
  panel_type VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  grid_x INT UNSIGNED NOT NULL DEFAULT 0,
  grid_y INT UNSIGNED NOT NULL DEFAULT 0,
  grid_w INT UNSIGNED NOT NULL DEFAULT 6,
  grid_h INT UNSIGNED NOT NULL DEFAULT 4,
  min_w INT UNSIGNED NOT NULL DEFAULT 2,
  min_h INT UNSIGNED NOT NULL DEFAULT 2,
  max_w INT UNSIGNED NULL,
  max_h INT UNSIGNED NULL,
  sort_order INT UNSIGNED NOT NULL DEFAULT 0,
  is_collapsed TINYINT(1) NOT NULL DEFAULT 0,
  is_locked TINYINT(1) NOT NULL DEFAULT 0,
  is_visible TINYINT(1) NOT NULL DEFAULT 1,
  is_resizable TINYINT(1) NOT NULL DEFAULT 1,
  is_draggable TINYINT(1) NOT NULL DEFAULT 1,
  visualization_config JSON NULL,
  query_config JSON NULL,
  display_config JSON NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  created_by BIGINT UNSIGNED NOT NULL,
  updated_at DATETIME(3) NULL,
  updated_by BIGINT UNSIGNED NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_dashboard_panels_guid (guid),
  KEY idx_dashboard_panels_tab (tab_id),
  KEY idx_dashboard_panels_tab_order (tab_id, sort_order),
  KEY idx_dashboard_panels_tab_status (tab_id, status),
  KEY idx_dashboard_panels_tab_position (tab_id, grid_y, grid_x),
  CONSTRAINT chk_dashboard_panels_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
  CONSTRAINT chk_dashboard_panels_version CHECK (version >= 1),
  CONSTRAINT chk_dashboard_panels_grid_w CHECK (grid_w >= min_w),
  CONSTRAINT chk_dashboard_panels_grid_h CHECK (grid_h >= min_h),
  CONSTRAINT fk_dashboard_panels_tab FOREIGN KEY (tab_id)
    REFERENCES dashboard_tabs (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
